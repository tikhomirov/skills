export function generateAgentsMd(projectId) {
  return `# AGENTS.md — ${projectId}

## Порядок чтения
1. Этот файл: правила, архитектура и карта проекта. Затем _statuses.md — единственный источник статусов задач и порядка колонок.
2. _agents/Memory/NOW.md: текущая задача, ограничения и следующий шаг.
3. Tasks/_INDEX.md (или существующая Задачи/_INDEX.md): найти карточку, проверить статус, связи и зависимости.
4. Прочитать _agents/Knowledge/Карта проекта.md, затем только нужные пользовательские модули и Решения/.

## Структура
- _шаблоны/: шаблоны задач, модулей, API, решений, отчётов и сообщений по компонентам приложения.
- _вложения/: изображения и другие вложения.
- _служебное/: проектные скрипты и генераторы; не выполнять неизвестные скрипты автоматически.
- Tasks/ (или существующая Задачи/): карточки TASK-NNN_<status>_<YYYY-MM-DD>.md, _INDEX.md и _Задачи.base — настоящая встроенная канбан-доска Obsidian 1.14+.
- _statuses.md: пользовательский реестр статусов с описаниями и ролями; порядок строк задаёт колонки канбана. Начальные значения: Backlog (backlog), In Progress (in-progress), Done (done). Пользователь вправе расширить и изменить их; агент не навязывает встроенный список.
- Решения/: append-only история решений пользователя с датами, источниками, id задач и связями между решениями. Не изменять и не удалять записи.
- _agents/: свободная рабочая зона агента. Базовые каталоги Memory/, Knowledge/, Reports/; при необходимости дополнительные каталоги, карта проекта и ссылки на скиллы.
- _agents/Memory/: NOW.md, STATE.md и sessions/ для передачи контекста.
- _agents/Knowledge/: исследования, карта проекта и генерируемый таймлайн решений.
- _agents/Reports/: результаты задач, проверки, коммиты и оставшиеся ограничения.
- Пользовательские модули: согласованные 01_Имя/, 02_Имя/ в корне при числе менее 10 либо раздел Модули/. API — возможный модуль, не обязательный корневой каталог.

## Архитектура и навигация по коду
Заполнить после исследования репозитория: стек, точки входа, компоненты, пути к коду,
тестам и команды запуска/проверки. Не выдумывать отсутствующие сведения.
Краткие подтверждённые сведения живут здесь. Рабочая карта — в _agents/Knowledge/Карта проекта.md.
Сначала спросить пользователя о составе, названиях и расположении модулей и дождаться подтверждения.
Документация модулей и Архитектура.md — только чтение; создавать и менять её можно лишь по явной просьбе пользователя.

## Инструменты и фреймворк
- Скилл obsidian: точный синтаксис и инструменты Obsidian.
- Скилл obsidian-project-framework: организация проекта и рабочий протокол.
- CLI obsidian-project-framework помогает соблюдать протокол; без скриптов выполнить те же действия вручную.

## Правила
- Один факт — один источник. Код определяет фактическое поведение; Решения/ — согласованные требования.
- Несоответствие кода решению показать пользователю, а не молча менять правило или выдавать код за согласованный.
- Сначала поиск по карте. Читать статус, updated, sources и review перед использованием заметки.
- Наблюдение агента не является решением пользователя. Предложения хранить в карточке задачи.
- Для разрешённых изменяемых заметок после правки: updated, sources и review: pending. Это не разрешает менять модули или историю решений.
- После изменения кода записать результаты в _agents/Knowledge и Reports. Нужную правку модульной документации предложить пользователю; до явной просьбы не выполнять.
- Решения пользователя дописывать отдельными событиями: что, когда, источник, на каких задачах принято. Новое решение может заменять старое ссылкой supersedes, но оригинал неизменяем.
- В Решения/ использовать стабильные id задач, не изменяемые имена карточек. Актуальные ссылки и таймлайн генерируются в _agents/Knowledge/Решения — таймлайн.md.
- У задачи обязательны id, title, summary, status, status_changed, tags, related, depends_on, sources.
- Дата в имени карточки — дата изменения статуса (UTC), не последней правки текста.
- Перед созданием и сменой статуса читать _statuses.md. Использовать только его идентификаторы; роли backlog/active/done определяют старт, работу и завершение. Изменение реестра — только по просьбе пользователя, затем task sync. Не удалять используемый статус без явного сопоставления задач.
- Перетаскивание карточки в Obsidian меняет только status. После него выполнить obsidian-project-framework task sync для имени, тегов, индекса и ссылок. До переноса в статус с ролью done подготовить отчёт и проверки.
- При смене статуса переименовать карточку, обновить status_changed, статусный тег, ссылки и индекс.
- Внешние ссылки и неизменяемые записи связывать со стабильным id задачи. Точные ссылки на карточки обновлять только в разрешённой рабочей зоне, не в модулях и Решения/.
- Завершать задачу только с результатом, отчётом и реальными проверками; отдельно указать несогласованные обновления модульной документации.
- Обновлять NOW/STATE и checkpoint в конце сессии: что сделано, что осталось, ограничения и следующий шаг.
- _INDEX.md и _Задачи.base — генерируемая навигация, не второй источник описаний задач.
- Команды идемпотентны: повтор с теми же данными не создаёт дубль и не меняет даты неизменившегося состояния.
- task create возвращает существующую задачу по --key (без ключа — по точному названию); новая одноимённая задача требует нового ключа.
- Повтор текущего статуса — no-op; повтор одинакового отчёта/checkpoint не дописывает журнал и не создаёт копию.
- --dry-run не создаёт даже каталоги. init не перезаписывает пользовательские правила и память.
- Не удалять исходные документы при миграции, не обходить симлинками границы проекта.
- Не копировать .env, пароли и токены в заметки, контекст и отчёты.
- Не коммитить, не пушить, не менять стенд и не публиковать материалы без разрешения пользователя.
`;
}
export function generateTasksBase(projectId, folder, statuses = DEFAULT_STATUSES) {
  return `filters:
  and:
    - 'file.inFolder(${JSON.stringify(folder)})'
    - 'type == "task"'
properties:
  title:
    displayName: "Задача"
  summary:
    displayName: "Описание"
  status:
    displayName: "Статус"
  status_changed:
    displayName: "Дата статуса"
views:
  - type: kanban
    name: "Канбан задач"
    groupBy:
      property: note.status
      direction: ASC
    groupOrder:
${statuses.map(status => `      - ${status.id}`).join('\n')}
    order:
      - title
      - summary
      - id
      - tags
`;
}
